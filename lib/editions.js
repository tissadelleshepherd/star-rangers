// ALIAS DOMAINS - recorded here on purpose, and deliberately NOT in any
// edition's `domains` array (confirmed with Dermot 2026-07-30):
//
// The list is now the ALIASES map below rather than prose in this comment.
//
// The four dated 2026-08-20 are the only ones here that were ever builds. Each
// failed the same clause of the build test in lib/editions.js's codex-site
// entry - no page set of its own, only framing - and each is more useful as an
// alias, where it cannot compete with the domain it was meant to point at.
// church-space.online is the instructive one: it was going to be a Cnoc na
// mBeach codex site until the measurement showed every Cnoc na mBeach page is
// church-space thread material, selectable only by naming the thread and never
// by tag. There was no filter that could give it a page set.
//
// They were builds, unlike the rest of this list. It is here
// under the rule that settled the duplicate-content question on 2026-08-20: a
// REGISTRATION DEFENDS THE NAME, A BUILD HAS TO EARN ITS KEEP. Promote a TLD to
// a build when it has a face of its own to show; until then an alias already
// does the anti-squatting job, and does it better - it cannot become a
// duplicate because it never had its own SITE_DOMAIN to self-canonicalise to.
//
// The five fianilchruinne aliases (added 2026-08-03, same day the .com went
// canonical) are spelling and TLD insurance around the canonical: the
// hyphenated form matches the umbrella's settled spelling Fian-ilchruinne,
// and the .site/.space/.online/.net set closes the obvious typo-TLD space.
// fianilchruinne.ie is NOT registered (not applied for as of 2026-08-03).
//
// These are cPanel aliases: they share their target's document root and serve
// its files, with no Eleventy build of their own. Nothing needs to resolve them,
// and self-canonical already does the right thing without being asked - the HTML
// they serve was built with the TARGET's SITE_DOMAIN, so a page at
// star-rangers.space already carries a canonical naming sciencefiction.site, and
// search engines consolidate to the target on their own.
//
// WHY LISTING THEM UNDER `domains` WOULD BE A TRAP. It would look tidy and would
// do nothing today, because no build asks about them. But `domains` is what
// scripts/resolve-edition.js matches, so the entry would sit there waiting: the
// day one of these was converted to an ALT_DOMAINS entry with its own build, it
// would resolve, build its own copy, and self-canonicalise to ITSELF - turning a
// correctly-consolidated alias into a genuine duplicate competing with the very
// domain it was meant to point at. Recording them as prose says the true thing
// (these hostnames exist and where they go) without arming that.
//
// If one ever does get its own build, the right move is a deliberate one: decide
// then whether it is an edition (give it its own copy, and self-canonical is
// correct) or still an alias (leave it an alias, or 301 it).

// The CONTEMPLATIVE tier's six domains share everything that decides what they
// carry and differ only in how they introduce it. Spread into each entry below
// rather than repeated, so the thread opt-in, the giscus board and the ranking
// host cannot drift apart across six records - which is exactly how the
// fellowship and church-space editions came to serve the identical 62 indexable
// pages without either entry showing it.
//
// WHAT A SPECIALISATION CAN AND CANNOT BE, measured 2026-08-20. It is FRAMING
// ONLY, and that is a property of the filter rather than a lack of ambition:
// lib/content-filter.js unions characters, topics and threads, so a page is in
// if it matches ANY of them. Adding `topics: ["communion-of-the-called"]` on
// top of `threads: ["church-space"]` changes the indexable count by nothing at
// all (62 to 62) because those pages are already inside the thread, and
// dropping the thread to narrow by the tag alone falls to 46 - the shared
// navigational shell, with Season 8 and the rest of the thread gone with it.
//
