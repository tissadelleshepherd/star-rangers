const TIER_ORDER = ["children", "young-adult", "general", "contemplative"];

function tierRank(tier) {
  const i = TIER_ORDER.indexOf(String(tier || "").toLowerCase());
  return i === -1 ? null : i;
}

// THE ONE TIER PREDICATE. Something that names a tier - a `::: pov` block
// (lib/markdown-containers.js), a storyline thread (lib/storyline-threads.js
// `tier`, since 2026-09-04) - is visible on a build when it names no tier, or
// names one at or below the build's own. Defined once here so the two gates
// cannot disagree about what "at or below" means. An unknown tier on either
// side reads as the general tier: the build side because that is where the
// canonical site sits, the item side because validate-content.js refuses an
// unknown tier in `povs:` and validateEditions/the registry tests refuse one
// on a thread, so a typo fails loudly there rather than hiding content.
function tierVisible(itemTier, buildTier) {
  if (!itemTier) return true;
  const item = tierRank(itemTier);
  const build = tierRank(buildTier);
  const generalRank = TIER_ORDER.indexOf("general");
  return (item === null ? generalRank : item) <= (build === null ? generalRank : build);
}

