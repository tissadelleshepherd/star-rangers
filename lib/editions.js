// The PRESENTATION MODES a domain may choose - the third axis, alongside
// identity (this file) and palette (`theme`). Registered here rather than left
// as a free string so a typo fails the build instead of quietly serving the
// default posture, and so this list is the one place the set is enumerated:
// src/css/main.css's "Presentation modes" section implements exactly these.
//
// WHAT THE AXIS IS FOR. `theme` answers "what colour is this domain" and this
// answers "how does this domain want to be read" - measure, leading, type
// size, density, how loud the chrome is. They were one question while every
// branded domain was the same kind of reading experience in different colours,
// and stopped being one when the codex site arrived: fellowshipoflight.site
// wants the Fellowship's palette and an index's density, which `theme` cannot
// say. The same shape as the split that produced this file, one level down.
//
// A MODE IS A POSTURE, NOT A TIER, and the mapping below is deliberately not
// one-to-one with the audience tiers in story-bible/story-bible-summary.md.
// The tiers are about register and POV-block length (children -> young adult ->
// general -> contemplative); a posture is about what the reader is doing.
// starquest.site is the young-adult tier and reads a story straight through
// exactly as the general tier does, so both are `story`; fellowshipoflight.site
// shares the fellowship's tier AND its palette and is still `archive`, because
// nobody reads a filing cabinet from the front.
//
// ADDING ONE is a real design decision, not configuration: a mode has to be a
// posture no existing mode serves, and it costs a block in main.css that every
// generated theme then carries. Wanting a domain to feel different is what the
// palette and the copy are for. Full reasoning, and the per-edition reader
// profile each of these was drawn from: story-bible/edition-reader-profiles.md.
//
// TWO NAMES PER MODE, and the split is deliberate. `summary` is the engine's
// name for what the mode is FOR - it names the edition's intent, and it is what
// a maintainer reads here. `label` is what a reader sees in the switcher
// (src/js/presentation.js), and it names only what the mode DOES to the page.
//
// A reader on the general-tier domain offered "Contemplative" would be being
// asked to identify with a devotional edition in order to get longer leading,
// which is both a strange thing to ask and a category error: the modes are
// postures, and a posture is not an allegiance. "Spacious" is the same setting
// described by its effect, which is the only thing the reader is choosing.
const PRESENTATION_MODES = {
  // Narrative read straight through - the site's default posture and the one
  // every domain had before this axis existed.
  story: {
    label: "Standard",
    summary: "Continuous narrative reading (the default posture)."
  },
  // Type up, line short, air between paragraphs: the children's tier's binding
  // constraint is completability, not comprehension.
  primer: {
    label: "Large print",
    summary: "Large type and a short measure for developing readers."
  },
  // Denser and wider, for a reader who came looking for a document rather than
  // a story.
  archive: {
    label: "Compact",
    summary: "Reference density for a filed record that is browsed, not read."
  },
  // The slowest setting on the site: long leading, narrow measure, quiet
  // headings.
  contemplative: {
    label: "Spacious",
    summary: "Unhurried measure and leading for devotional reading."
  }
};

