// An untracked, gitignored editions.local.json in the repo root, for anyone
// hosting this site independently. Exactly the pattern giscus.local.json
// already establishes (see src/_data/giscus.js), and for the same reason:
// registering your own domain should not require editing a tracked engine file,
// because that means maintaining a fork and re-resolving a conflict on every
// upstream merge. Template: sample-editions.local.json.
//
// Shape: { "editions": [ { "id": "...", "domains": [...], ...overrides } ] }
//
// An entry whose id matches one below OVERRIDES it (merged over, field by
// field); a new id is added. So an independent host can either re-point an
// existing edition at their own domain or declare their own outright.
//
// The canon rule still binds a local file completely - there is no field here
// that can add lore, and that is deliberate. It means an independent host
// cannot publish their own material as this story's canon even by accident,
// which protects them as much as it protects the record.
const LOCAL_CONFIG_PATH = path.join(__dirname, "..", "editions.local.json");

let localCache; // undefined = not yet read, null = absent

function loadLocalEditions() {
  if (localCache !== undefined) return localCache;

  let raw;
  try {
    raw = fs.readFileSync(LOCAL_CONFIG_PATH, "utf8");
  } catch (err) {
    if (err.code === "ENOENT") { localCache = null; return localCache; }
    throw err;
  }

  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch (err) {
    throw new Error(`lib/editions.js: editions.local.json is not valid JSON - ${err.message}`);
  }
  const list = parsed && parsed.editions;
  if (!Array.isArray(list)) {
    throw new Error(
      "lib/editions.js: editions.local.json must be { \"editions\": [ ... ] }. " +
      "See sample-editions.local.json for the expected shape."
    );
  }
  for (const e of list) {
    if (!e || typeof e.id !== "string" || !e.id.trim()) {
      throw new Error("lib/editions.js: every entry in editions.local.json needs a non-empty string `id`.");
    }
  }
  localCache = list;
  return localCache;
}

/**
 * The tracked registry with any editions.local.json entries merged in.
 * @returns {object[]} edition records (not yet merged over DEFAULT_EDITION)
 */
function allEditions() {
  const local = loadLocalEditions();
  if (!local || !local.length) return EDITIONS;

  const byId = new Map(EDITIONS.map((e) => [e.id, e]));
  for (const entry of local) {
    const id = entry.id.trim().toLowerCase();
    byId.set(id, { ...(byId.get(id) || {}), ...entry, id });
  }
  return [...byId.values()];
}

/**
 * Merge an edition over DEFAULT_EDITION so callers always get a complete
 * record and an entry only has to declare what it changes. Shallow by design:
 * `themeAudio` is replaced wholesale rather than merged key-by-key, because a
 * half-overridden audio player (new label, old file) is never what anyone
 * means.
 *
 * @param {string} id
 * @returns {object} complete edition record; DEFAULT_EDITION for an unknown id
 */
const READING_PLAN_TEXT_FIELDS = ["intro", "begin", "howToRead", "more"];
const READING_PLAN_SHELVES = ["characters", "glossary", "timeline", "codex", "lore", "atlas"];

/**
 * Check one edition's optional `readingPlan` (null is fine). Exported so it
 * can be unit-tested with hand-built editions; validateEditions calls it for
 * every registered one.
 *
 * The failure it exists for is quiet: src/start/index.md resolves
 * `startThreadId` against the build's filtered chapters, so a thread this
 * edition's own narrowing excludes would render "Begin here" with no chapter
 * under it and the page would look merely unfinished. An unregistered id
 * fails the same way one step earlier. Both are refused here instead.
 *
 * @param {object} edition a merged edition (DEFAULT_EDITION spread first)
 * @throws {Error} on a malformed plan
 */
/**
 * Check one edition's optional `seasonsIntro` (null is fine): an array of
 * non-empty paragraph strings, rendered by src/seasons/index.md in place of
 * the site-wide intro. Added 2026-09-13.
 *
 * @param {object} edition a merged edition (DEFAULT_EDITION spread first)
 * @throws {Error} on a malformed intro
 */
function validateSeasonsIntro(edition) {
  const intro = edition.seasonsIntro;
  if (intro == null) return;
  const where = `lib/editions.js: edition "${edition.id}" seasonsIntro`;
  if (!Array.isArray(intro) || intro.length === 0) {
    throw new Error(`${where} must be a non-empty array of paragraph strings, or null.`);
  }
  intro.forEach((para, i) => {
    if (typeof para !== "string" || !para.trim()) {
      throw new Error(`${where}[${i}] must be a non-empty string.`);
    }
  });
}

const ABOUT_FIELDS = ["title", "intro", "grownUpsTitle", "grownUps"];

/**
 * Check one edition's optional `about` (null is fine): a title, a heading for
 * the grown-ups block, and two non-empty arrays of paragraph strings,
 * rendered by src/about/index.md in place of the site-wide page. Nothing
 * else - a field the template does not read would be a silent no-op, like an
 * excludedNotice link. Added 2026-09-14.
 *
 * @param {object} edition a merged edition (DEFAULT_EDITION spread first)
 * @throws {Error} on a malformed about
 */
function validateAbout(edition) {
  const about = edition.about;
  if (about == null) return;
  const where = `lib/editions.js: edition "${edition.id}" about`;
  if (typeof about !== "object" || Array.isArray(about)) {
    throw new Error(`${where} must be an object or null.`);
  }
  for (const key of Object.keys(about)) {
    if (!ABOUT_FIELDS.includes(key)) {
      throw new Error(`${where} has unknown field "${key}"; src/about/index.md reads ${ABOUT_FIELDS.join(", ")}.`);
    }
  }
  for (const field of ["title", "grownUpsTitle"]) {
    if (typeof about[field] !== "string" || !about[field].trim()) {
      throw new Error(`${where}.${field} must be a non-empty string.`);
    }
  }
  for (const field of ["intro", "grownUps"]) {
    const paras = about[field];
    if (!Array.isArray(paras) || paras.length === 0) {
      throw new Error(`${where}.${field} must be a non-empty array of paragraph strings.`);
    }
    paras.forEach((para, i) => {
      if (typeof para !== "string" || !para.trim()) {
        throw new Error(`${where}.${field}[${i}] must be a non-empty string.`);
      }
    });
  }
}

function validateReadingPlan(edition) {
  const plan = edition.readingPlan;
  if (plan == null) return;
  const where = `lib/editions.js: edition "${edition.id}" readingPlan`;
  if (typeof plan !== "object" || Array.isArray(plan)) {
    throw new Error(`${where} must be an object or null.`);
  }
  for (const field of READING_PLAN_TEXT_FIELDS) {
    if (typeof plan[field] !== "string" || !plan[field].trim()) {
      throw new Error(`${where}.${field} must be a non-empty string.`);
    }
  }
  if (typeof plan.shelves !== "object" || plan.shelves === null || Array.isArray(plan.shelves)) {
    throw new Error(`${where}.shelves must be an object keyed by section.`);
  }
  for (const key of Object.keys(plan.shelves)) {
    if (!READING_PLAN_SHELVES.includes(key)) {
      throw new Error(
        `${where}.shelves has unknown section "${key}"; src/start/index.md renders ${READING_PLAN_SHELVES.join(", ")}.`
      );
    }
    if (typeof plan.shelves[key] !== "string" || !plan.shelves[key].trim()) {
      throw new Error(`${where}.shelves.${key} must be a non-empty string.`);
    }
  }
  const threadId = String(plan.startThreadId || "").trim().toLowerCase();
  if (!STORYLINE_THREADS.some((t) => t.id === threadId)) {
    throw new Error(
      `${where}.startThreadId "${plan.startThreadId}" is not a registered thread in lib/storyline-threads.js.`
    );
  }
  // Same union lib/content-filter.js matches against. An empty union is the
  // unfiltered site, which carries every thread; otherwise the thread has to
  // be named, because a season is included by thread membership and nothing
  // else in the union can stand in for that.
  const narrowed = (edition.threads || []).length || (edition.characters || []).length || (edition.topics || []).length;
  if (narrowed && !(edition.threads || []).map((t) => String(t).toLowerCase()).includes(threadId)) {
    throw new Error(
      `${where}.startThreadId "${threadId}" is not in this edition's own threads [${(edition.threads || []).join(", ")}], ` +
      `so "Begin here" would have no chapter to open on.`
    );
  }
}

// The section pages whose templates consult edition.sectionHeroes. A key
// outside this list would validate, ship, and change nothing.
const SECTION_HERO_KEYS = ["characters"];

/**
 * Check one edition's optional `sectionHeroes` (null is fine). Exported so
 * it can be unit-tested with hand-built editions; validateEditions calls it
 * for every registered one.
 *
 * @param {object} edition a merged edition (DEFAULT_EDITION spread first)
 * @param {string} [heroDir] absolute path to src/images/hero; when given,
 *   each named file must exist there and must not be a PLACEHOLDER-stamped
 *   card - an override that puts the pending card back is the one thing the
 *   field exists to get past.
 * @throws {Error} on a malformed entry
 */
function validateSectionHeroes(edition, heroDir) {
  const heroes = edition.sectionHeroes;
  if (heroes == null) return;
  const where = `lib/editions.js: edition "${edition.id}" sectionHeroes`;
  if (typeof heroes !== "object" || Array.isArray(heroes)) {
    throw new Error(`${where} must be an object keyed by section, or null.`);
  }
  for (const [key, hero] of Object.entries(heroes)) {
    if (!SECTION_HERO_KEYS.includes(key)) {
      throw new Error(`${where} has unknown section "${key}"; templates consult ${SECTION_HERO_KEYS.join(", ")}.`);
    }
    if (typeof hero !== "object" || hero === null) {
      throw new Error(`${where}.${key} must be an object with image and alt.`);
    }
    if (typeof hero.image !== "string" || !hero.image.trim() || hero.image.includes("/")) {
      throw new Error(`${where}.${key}.image must be a bare filename in src/images/hero/.`);
    }
    if (typeof hero.alt !== "string" || !hero.alt.trim()) {
      throw new Error(`${where}.${key}.alt must be a non-empty description of what the file shows.`);
    }
    if (heroDir) {
      const file = path.join(heroDir, hero.image);
      if (!fs.existsSync(file)) {
        throw new Error(`${where}.${key}.image "${hero.image}" is not in ${heroDir}.`);
      }
      if (isPlaceholderImage(file)) {
        throw new Error(`${where}.${key}.image "${hero.image}" is a PLACEHOLDER-stamped pending card.`);
      }
    }
  }
}

