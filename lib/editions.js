// Returns the host this domain is an alias OF, or "" if this project has no
// opinion about it - which includes every third-party domain.
function aliasFor(domain) {
  return ALIASES[bareHost(domain)] || "";
}

// The inverse: every alias host that points AT this domain, sorted. Feeds the
// host-conditional 301 block scripts/cpanel-deploy.sh appends to a docroot's
// .htaccess (via resolve-edition.js's RESOLVED_ALIASES), because a parked
// alias shares its target's document root and would otherwise serve a full
// copy of the site under its own name. Google handled those copies correctly
// through the cross-domain canonical, but crawled every one of them - the
// 9 October 2026 Search Console sweep found 885 URLs known on star-rangers.site
// alone - and the ALIAS DOMAINS block above already says an alias is a 301,
// never a second build. Empty for a domain nothing points at.
function aliasesOf(domain) {
  const target = bareHost(domain);
  if (!target) return [];
  return Object.keys(ALIASES)
    .filter((alias) => ALIASES[alias] === target)
    .sort();
}

