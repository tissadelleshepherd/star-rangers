function editionFor(id) {
  const wanted = String(id || "").trim().toLowerCase();
  const found = allEditions().find((e) => e.id === wanted);
  return found ? { ...DEFAULT_EDITION, ...found } : { ...DEFAULT_EDITION };
}

/**
 * Look an edition up by the domain it serves.
 *
 * Matching is on the bare host, case-insensitively, with any scheme, `www.`,
 * port, path and trailing slash stripped first - so "https://Church-Space.site/"
 * and "church-space.site" are the same domain. A path-bearing entry (the
 * GitHub Pages one, "dermot-r-cochran.github.io/star-rangers") is matched on
 * its host part too, since a host cannot serve two editions.
 *
 * Returns null rather than DEFAULT_EDITION on no match, so a caller can tell
 * "this domain is registered as the default edition" apart from "this domain is
 * not registered at all" - the deploy log says which, and a silent default is
 * how a domain ends up quietly serving the wrong thing.
 *
 * @param {string} domain
 * @returns {object|null} complete edition record, or null if unregistered
 */
function editionForDomain(domain) {
  const host = bareHost(domain);
  if (!host) return null;
  const all = [DEFAULT_EDITION, ...allEditions()];
  const found = all.find((e) => (e.domains || []).some((d) => bareHost(d) === host));
  return found ? { ...DEFAULT_EDITION, ...found } : null;
}

function bareHost(value) {
  return String(value || "")
    .trim()
    .toLowerCase()
    .replace(/^[a-z]+:\/\//, "")
    .replace(/^www\./, "")
    .split("/")[0]
    .split(":")[0];
}

/**
 * Resolve the edition for this build from the environment.
 *
 * EDITION wins; THEME is the migration fallback (see MIGRATION SAFETY above);
 * an unset or unrecognised value yields DEFAULT_EDITION. Deliberately does NOT
 * throw on an unknown id, unlike GISCUS_PROFILE in src/_data/giscus.js - a
 * wrong giscus profile silently attaches reader comments to the wrong repo,
 * which is unrecoverable, whereas a wrong edition id costs a domain its
 * tagline and is obvious on the homepage.
 *
 * @returns {object} complete edition record
 */
function getEdition() {
  return editionFor(process.env.EDITION || process.env.THEME);
}

/**
 * Fail the build on a malformed registry. Called from .eleventy.js at config
 * time, so a mistake here stops the build instead of shipping a broken page.
 *
 * This exists because moving copy out of src/ cost some automatic checking,
 * and the loss should be paid back rather than absorbed. Two specifics:
 *
 *   - `themeAudio.file` used to appear in base.njk as a literal audio src
 *     under /star-rangers/audio/, which scripts/check-internal-links.js
 *     verified. It is now a bare filename assembled by a template, so that
 *     script skips it as a templated href - a typo would ship a player
 *     pointing at nothing. Checked against src/audio/ here instead.
 *     (Deliberately described rather than quoted as a path: that script now
 *     scans this file, and a made-up example URL in a comment would fail it -
 *     as one did while this was being written.)
 *   - `heroSubtitle` links ARE still covered: check-internal-links.js now
 *     scans this file by name (see its EXTRA_FILES).
 *
 * Duplicate ids are checked too: EDITIONS_BY_ID would silently keep the last
 * one, the same quiet-wrong-answer failure validate-content.js guards against
 * for chapter comment_id collisions.
 *
 * @param {string} audioDir absolute path to the directory holding audio files
 * @throws {Error} on a duplicate id, or an audio file that isn't there
 */
function validateEditions({ audioDir, cssDir, heroDir }) {
  const all = [DEFAULT_EDITION, ...allEditions()];

  const seenIds = new Set();
  for (const e of all) {
    if (seenIds.has(e.id)) {
      throw new Error(`lib/editions.js: duplicate edition id "${e.id}" - only one of them would ever be used.`);
    }
    seenIds.add(e.id);
  }

  // A domain claimed by two editions is the worst failure mode this file has:
  // resolution would pick whichever came first and the other domain would
  // quietly serve the wrong branding forever. Cheap to rule out here.
  const seenDomains = new Map();
  for (const e of all) {
    for (const d of e.domains || []) {
      const host = bareHost(d);
      if (seenDomains.has(host)) {
        throw new Error(
          `lib/editions.js: domain "${host}" is claimed by both "${seenDomains.get(host)}" and "${e.id}".`
        );
      }
      seenDomains.set(host, e.id);
    }
  }

  // A ranksAt naming a host no edition serves is a total, silent failure: every
  // page on every sibling would canonical to a URL nothing builds, and the
  // family's whole content would drop out of the index while the deploy logs
  // success. The typo and the deleted-entry cases both land here.
  for (const e of all) {
    if (!e.ranksAt) continue;
    const host = bareHost(e.ranksAt);
    if (!seenDomains.has(host)) {
      throw new Error(
        `lib/editions.js: edition "${e.id}" has ranksAt "${host}", which no edition claims in its domains. ` +
        `Every page on this domain would canonical to a host nothing builds.`
      );
    }
    // The invariant behind ranksAt: the ranking domain must include every page
    // its siblings include, or a canonical points at a noindex placeholder and
    // the page is lost. Can't be fully checked without building both, but the
    // filters being a SUPERSET is necessary, and the common way to break it is
    // narrowing the ranking domain rather than the siblings.
    const target = all.find((x) => (x.domains || []).some((d) => bareHost(d) === host));
    if (target && target !== e) {
      // Compare the UNION of all three axes, not each axis separately, because
      // that union is exactly what lib/content-filter.js matches against
      // (`tagMatches`). Testing per-axis got this wrong in the obvious
      // direction: an empty `topics` on the ranking domain looks like "no
      // narrowing on this axis" and was skipped, but a domain filtering by
      // threads is still narrowed - so a sibling carrying topics the ranking
      // domain does not would have passed while pointing its canonicals at
      // pages that render there as noindex placeholders.
      const union = (x) => [...(x.threads || []), ...(x.characters || []), ...(x.topics || [])];
      const theirs = union(target);
      // An empty union really is unfiltered - the full site includes everything.
      if (theirs.length) {
        const missing = union(e).filter((v) => !theirs.includes(v));
        if (missing.length) {
          throw new Error(
            `lib/editions.js: edition "${e.id}" ranks at "${host}" but filters on [${missing.join(", ")}], ` +
            `which "${target.id}" does not carry. The ranking domain must be a superset - ` +
            `narrow the siblings, never the one that ranks.`
          );
        }
      }
    }
  }

  // An alias that is also a served domain is a contradiction, and the harmful
  // direction is obvious: the edition would resolve, the domain would build its
  // own copy, and it would self-canonicalise against the very host it was meant
  // to point at. Same trap the commentary above warns about, now checkable.
  for (const [host, target] of Object.entries(ALIASES)) {
    if (seenDomains.has(host)) {
      throw new Error(
        `lib/editions.js: "${host}" is listed as an alias of "${target}" and is also served by ` +
        `edition "${seenDomains.get(host)}". It cannot be both.`
      );
    }
    if (!seenDomains.has(bareHost(target))) {
      throw new Error(
        `lib/editions.js: alias "${host}" points at "${target}", which no edition serves. ` +
        `An alias must point at a domain that is actually built.`
      );
    }
  }

  // An unregistered presentation mode is silent in the worst way: the
  // attribute lands on <html>, no CSS block matches it, and the domain serves
  // the default posture looking entirely healthy. Cheaper to refuse it here.
  for (const e of all) {
    const mode = e.presentation || DEFAULT_EDITION.presentation;
    if (!Object.prototype.hasOwnProperty.call(PRESENTATION_MODES, mode)) {
      throw new Error(
        `lib/editions.js: edition "${e.id}" names presentation mode "${mode}", which is not one of ` +
        `${Object.keys(PRESENTATION_MODES).join(", ")}. src/css/main.css implements exactly those.`
      );
    }
  }

  // And a mode this file registers but main.css never implements fails the
  // same way one step further along - so the registry and the stylesheet are
  // checked against each other rather than each being checked alone. "story"
  // is the absence of a block by design (it IS main.css's own values), so only
  // the others are looked for. Reads main.css and not the generated themes:
  // scripts/generate-themes.js copies everything outside :root verbatim, so a
  // block present there is present in all of them.
  if (cssDir) {
    const mainCss = fs.readFileSync(path.join(cssDir, "main.css"), "utf8");
    for (const mode of Object.keys(PRESENTATION_MODES)) {
      if (mode === "story") continue;
      if (!mainCss.includes(`[data-presentation="${mode}"]`)) {
        throw new Error(
          `lib/editions.js: presentation mode "${mode}" is registered here but src/css/main.css ` +
          `has no [data-presentation="${mode}"] rules - a domain choosing it would silently ` +
          "get the default posture."
        );
      }
    }
  }

  // THE TIER LADDER must actually nest. Each tier's filter union must contain
  // the union of the tier below it, and every reading edition (anything that
  // narrows and is not a codex site) must carry at least its tier's filters.
  // An entry that overrides `threads:` or `topics:` after spreading its tier
  // is the way this breaks, and it would narrow a live domain silently.
  const unionOf = (x) => new Set([...(x.threads || []), ...(x.characters || []), ...(x.topics || [])]);
  for (let i = 1; i < TIER_ORDER.length; i++) {
    const lower = unionOf(TIERS[TIER_ORDER[i - 1]]);
    const upper = unionOf(TIERS[TIER_ORDER[i]]);
    for (const v of lower) {
      if (!upper.has(v)) {
        throw new Error(
          `lib/editions.js: tier "${TIER_ORDER[i]}" does not carry "${v}" from tier "${TIER_ORDER[i - 1]}" - the tiers must nest.`
        );
      }
    }
  }
  for (const e of all) {
    if (!e.tier) {
      throw new Error(`lib/editions.js: edition "${e.id}" names no tier. Every edition sits somewhere on TIER_ORDER.`);
    }
    if (!TIER_ORDER.includes(e.tier)) {
      throw new Error(`lib/editions.js: edition "${e.id}" names tier "${e.tier}", which is not one of ${TIER_ORDER.join(", ")}.`);
    }
    const own = unionOf(e);
    if (!own.size) continue; // unfiltered: holds everything, trivially a superset
    if (e.codexSite) continue; // a shelf, narrowed on purpose - outside the ladder
    for (const v of unionOf(TIERS[e.tier])) {
      if (!own.has(v)) {
        throw new Error(
          `lib/editions.js: edition "${e.id}" is on tier "${e.tier}" but does not carry "${v}", which that tier carries. ` +
          `Extend the tier's lists (\`[...${e.tier === "contemplative" ? "CONTEMPLATIVE_TIER" : "TIER"}.topics, ...]\`), never replace them.`
        );
      }
    }
  }

  for (const e of all) validateReadingPlan(e);
  for (const e of all) validateSeasonsIntro(e);
  for (const e of all) validateSectionHeroes(e, heroDir);
  for (const e of all) validateExcludedNotice(e);
  for (const e of all) validateAbout(e);

  for (const e of all) {
    const file = (e.themeAudio || DEFAULT_EDITION.themeAudio).file;
    if (!fs.existsSync(path.join(audioDir, file))) {
      throw new Error(
        `lib/editions.js: edition "${e.id}" names themeAudio.file "${file}", which is not in ${audioDir}.`
      );
    }
    // A typo'd theme name is not otherwise loud: cpanel-deploy.sh checks the
    // file exists and silently keeps main.css when it doesn't, so the domain
    // deploys looking unbranded rather than failing.
    const theme = e.theme || DEFAULT_EDITION.theme;
    if (cssDir && theme !== "default" && !fs.existsSync(path.join(cssDir, `theme-${theme}.css`))) {
      throw new Error(
        `lib/editions.js: edition "${e.id}" names theme "${theme}", but ${path.join(cssDir, `theme-${theme}.css`)} does not exist.`
      );
    }
  }
}

